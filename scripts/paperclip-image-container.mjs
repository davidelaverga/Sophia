#!/usr/bin/env node
// WBC-02 (WBC-02-CC-0013, CX-0032): the disposable Paperclip container of the image qualification, on loopback only:
//   node scripts/paperclip-image-container.mjs start <label> [signup-closed]   run it under the 2 GiB ceiling and wait
//                                                                           (300 s at most) until it reports healthy
//   node scripts/paperclip-image-container.mjs restart <label>              docker restart (the container was stopped for
//                                                                           the home's snapshot: it starts again), then
//                                                                           the same wait
//   node scripts/paperclip-image-container.mjs stop                         docker stop (30 s of grace), before each
//                                                                           home snapshot a transition starts from
//                                                                           (reviews of 2bad104 and cc0ffbb)
//   node scripts/paperclip-image-container.mjs remove
//   node scripts/paperclip-image-container.mjs diagnostics <dir>             bounded, redacted logs and state
// The image is $IMAGE; the database ($DATABASE_URL, a disposable PostgreSQL on the job's own network) and the
// credentials are generated by the job and passed to docker by name (`-e NAME`), so no value is on a command line.
// The container runs with Docker's default capability set, not narrowed here (whether a hosting platform narrows it is
// not what this qualifies), not privileged, on the job's network and not the host's; its port is published on
// 127.0.0.1 only. After each start and restart, what Docker actually configured (privileged, added and dropped
// capabilities, network, published ports) is appended to $EVIDENCE/runtime.jsonl, and the receipt checks it (review of
// 9130676). Sophia's address is closed (nothing listens on 127.0.0.1:9 in the container). Each wait appends its
// seconds, measured on a monotonic clock, and outcome to $EVIDENCE/timings.jsonl.
import { execFileSync, spawnSync } from 'node:child_process'
import { appendFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { exchange } from './paperclip-probe-http.mjs'

const NAME = 'pc'
const PORT = 3100
const HEALTH_DEADLINE_MS = 300_000
const CREDENTIALS = [
  'DATABASE_URL',
  'BETTER_AUTH_SECRET',
  'PAPERCLIP_SECRETS_MASTER_KEY',
  'PAPERCLIP_TOOL_ACTION_SIGNING_SECRET',
  'PAPERCLIP_DECISION_SIGNING_SECRET',
  'SOPHIA_COORDINATION_TOKEN',
]

const docker = (args, timeout = 120_000) =>
  execFileSync('docker', args, { encoding: 'utf8', timeout, maxBuffer: 8 * 1024 * 1024 }).trim()
const sleep = (ms) => new Promise((done) => setTimeout(done, ms))
const evidence = process.env.EVIDENCE ?? '.'

/**
 * One health read, settled within 5 s whatever the server does (scripts/paperclip-probe-http.mjs, WBC-02-CX-0037): the
 * HTTP status and the status the server reported, recorded so the receipt judges what was observed (review of
 * 4c63217); null when nothing answered.
 */
async function health() {
  try {
    const reply = await exchange({ port: PORT, path: '/api/health', timeoutMs: 5000 })
    return { status: reply.status, reported: typeof reply.json?.status === 'string' ? reply.json.status : null }
  } catch {
    return null
  }
}

/** The container's whole log, both streams, kept in memory to be counted: never printed here. */
function logsOf() {
  const run = spawnSync('docker', ['logs', NAME], { encoding: 'utf8', timeout: 60_000, maxBuffer: 32 * 1024 * 1024 })
  return `${run.stdout ?? ''}${run.stderr ?? ''}`
}

/** What Docker configured for the container: privilege, capabilities, network, published ports; no environment. */
function recordRuntime(label) {
  const host = JSON.parse(docker(['inspect', '--format', '{{json .HostConfig}}', NAME], 20_000))
  const ports = Object.entries(host.PortBindings ?? {}).flatMap(([port, binds]) =>
    (binds ?? []).map((bind) => ({ port, hostIp: bind.HostIp, hostPort: bind.HostPort })),
  )
  const record = {
    label,
    privileged: host.Privileged,
    capAdd: host.CapAdd ?? [],
    capDrop: host.CapDrop ?? [],
    networkMode: host.NetworkMode,
    securityOpt: host.SecurityOpt ?? [],
    ports,
  }
  appendFileSync(join(evidence, 'runtime.jsonl'), `${JSON.stringify(record)}\n`)
}

/**
 * Waits for health, at most HEALTH_DEADLINE_MS; stops early if the container is no longer running. `started` is a
 * performance.now() reading: a monotonic clock, so a wall-clock step cannot make a start look shorter or negative.
 * At most about 407 s in all: the window (300 s), one last read and check begun inside it (27 s), the log (60 s) and
 * the health inspect (20 s); the workflow's `timeout` for each start is above that.
 */
async function waitHealthy(label, started) {
  let ok = false
  let reason = 'deadline'
  let last = null
  while (performance.now() - started < HEALTH_DEADLINE_MS) {
    last = await health()
    if (last?.status === 200 && last.reported === 'ok') {
      ok = true
      break
    }
    if (docker(['inspect', '--format', '{{.State.Running}}', NAME], 20_000) !== 'true') {
      reason = 'container exited'
      break
    }
    await sleep(2000)
  }
  // Taken as the wait ends, before the diagnostics below: reading a large log can take up to a minute, and that is not
  // the start's time (Codex review of 37bae0e).
  const seconds = Math.round((performance.now() - started) / 100) / 10
  const logs = logsOf()
  const record = {
    label,
    ok,
    seconds,
    health: last,
    ...(ok ? {} : { reason }),
    dockerHealth: docker(['inspect', '--format', '{{if .State.Health}}{{.State.Health.Status}}{{end}}', NAME], 20_000),
    adapterLogLines: logs.split('\n').filter((l) => l.includes('sophia_dsh')).length,
  }
  appendFileSync(join(evidence, 'timings.jsonl'), `${JSON.stringify(record)}\n`)
  console.log(`[container] ${label}: ${ok ? 'healthy' : `not healthy (${reason})`} after ${record.seconds} s`)
  if (!ok) process.exitCode = 1
}

const [mode, label, extra] = process.argv.slice(2)
if (mode === 'start') {
  for (const name of CREDENTIALS) if (!process.env[name]) throw new Error(`${name} is not set`)
  const started = performance.now()
  docker([
    'run',
    '--detach',
    '--name',
    NAME,
    '--network',
    'pcnet',
    '--memory=2g',
    '--memory-swap=2g',
    '--publish',
    `127.0.0.1:${PORT}:${PORT}`,
    '--volume',
    'pchome:/paperclip',
    ...CREDENTIALS.flatMap((name) => ['--env', name]),
    '--env',
    'PAPERCLIP_ALLOWED_HOSTNAMES=paperclip-private',
    '--env',
    'SOPHIA_COORDINATION_URL=http://127.0.0.1:9',
    ...(extra === 'signup-closed' ? ['--env', 'PAPERCLIP_AUTH_DISABLE_SIGN_UP=true'] : []),
    process.env.IMAGE ?? 'sophia-paperclip:candidate',
  ])
  recordRuntime(label)
  await waitHealthy(label, started)
} else if (mode === 'restart') {
  const started = performance.now()
  docker(['restart', '-t', '30', NAME])
  recordRuntime(label)
  await waitHealthy(label, started)
} else if (mode === 'stop') {
  // Stopped before the home snapshot a transition starts from, so nothing writes between that scan and the restart or
  // the removal (reviews of 2bad104 and cc0ffbb).
  docker(['stop', '-t', '30', NAME], 90_000)
} else if (mode === 'remove') {
  docker(['rm', '--force', NAME])
} else if (mode === 'diagnostics') {
  mkdirSync(label, { recursive: true })
  const capture = (args) => {
    try {
      return execFileSync('docker', args, { encoding: 'utf8', timeout: 60_000, maxBuffer: 8 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] })
    } catch (error) {
      return `${error.stdout ?? ''}${error.stderr ?? ''}${error.message}`
    }
  }
  const redact = (text) =>
    execFileSync(process.execPath, [join(import.meta.dirname, 'paperclip-image-redact.mjs')], {
      input: text,
      encoding: 'utf8',
      env: { ...process.env, REDACT_VARS: [...CREDENTIALS, 'PCDB_PASSWORD'].join(',') },
    })
  // The state only: never `docker inspect` in full, whose Config.Env holds the credentials.
  writeFileSync(join(label, 'containers.txt'), redact(capture(['ps', '--all', '--format', '{{.Names}} {{.Image}} {{.Status}}'])))
  writeFileSync(join(label, 'pc-state.json'), redact(capture(['inspect', '--format', '{{json .State}}', NAME])))
  writeFileSync(join(label, 'pc-logs.txt'), redact(capture(['logs', '--tail', '400', NAME])))
  writeFileSync(join(label, 'pcdb-logs.txt'), redact(capture(['logs', '--tail', '100', 'pcdb'])))
  console.log(`[container] redacted diagnostics in ${label}`)
} else {
  throw new Error('usage: paperclip-image-container.mjs start <label> [signup-closed] | restart <label> | stop | remove | diagnostics <dir>')
}
