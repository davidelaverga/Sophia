#!/usr/bin/env node
// Generate standalone validators for the responses a client reads, from openapi/openapi.json.
// Ajv compiles them here, with the API's own options but one, so no browser needs Ajv or eval at runtime. That one: a
// reader drops a property its schema doesn't list instead of refusing it, so a client built before an additive
// amendment reads the newer API as the shape it knows (docs/plans/tolerant-readers.md).
//   node scripts/generate-validators.ts          write src/generated/validators.js and .d.ts
//   node scripts/generate-validators.ts --check  fail if either file is out of date
