const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const targets = { code: join(root, 'src/generated/validators.js'), types: join(root, 'src/generated/validators.d.ts') }
const HEADER =
  '// Generated by packages/contracts/scripts/generate-validators.ts from openapi/openapi.json; do not edit.'

/**
 * The API's Ajv options (apps/api/src/app.ts) plus the same full format set Fastify installs, except that a reader drops
 * what `additionalProperties: false` doesn't list (the API's own request validation keeps refusing it).
 */
function compiler(): Ajv {
  const ajv = new Ajv({
    schemas: componentSchemas(),
    strict: true,
    allErrors: false,
    removeAdditional: true,
    coerceTypes: false,
    useDefaults: false,
    code: { source: true, esm: true },
  })
  addFormats.default(ajv, { mode: 'full' })
  // ajv-formats emits require() for format functions; name an ES import instead.
  ajv.opts.code.formats = _`fullFormats`
  return ajv
}

type Schema = Record<string, unknown>

const isRecord = (node: unknown): node is Schema => typeof node === 'object' && node !== null && !Array.isArray(node)

/** A reference's component name: `Goal#` as the compiler names it. */
const refName = (ref: string): string => ref.replace(/#$/, '').split('/').at(-1) ?? ''

/** The component schemas a reader reaches, by name, through its references. */
function reached(schemas: Record<string, Schema>): string[] {
  const seen = new Set<string>()
  const refs = (node: unknown): string[] => {
    if (Array.isArray(node)) return node.flatMap(refs)
    if (typeof node !== 'object' || node === null) return []
    return Object.entries(node).flatMap(([k, v]) => (k === '$ref' && typeof v === 'string' ? [refName(v)] : refs(v)))
  }
  const queue: string[] = [...EXPORTS]
  for (let name = queue.pop(); name !== undefined; name = queue.pop()) {
    if (seen.has(name)) continue
    seen.add(name)
    queue.push(...refs(schemas[name]))
  }
  return [...seen]
}

/**
 * Dropping is safe only where a value meets one object schema: Ajv drops while trying an `anyOf` branch, even one that
 * then fails, so a second object branch could find its fields gone. Refuse to generate a reader over such a union.
 */
function assertDropSafe(): void {
  const schemas: Record<string, Schema> = Object.fromEntries(componentSchemas().map((s) => [s.$id, s]))
  const objectLike = (node: unknown): boolean => {
    if (!isRecord(node)) return false
    const target = typeof node.$ref === 'string' ? schemas[refName(node.$ref)] : node
    return target !== undefined && (target.type === 'object' || 'properties' in target || 'anyOf' in target)
  }
  const unions: string[] = []
  const walk = (node: unknown, at: string): void => {
    if (Array.isArray(node)) return node.forEach((v, i) => walk(v, `${at}/${String(i)}`))
    if (!isRecord(node)) return
    const branches = node.anyOf
    if (Array.isArray(branches) && branches.filter(objectLike).length > 1) unions.push(at)
    for (const [k, v] of Object.entries(node)) walk(v, `${at}/${k}`)
  }
  for (const name of reached(schemas)) walk(schemas[name], name)
  if (unions.length > 0) throw new Error(`a reader would drop fields inside a union of objects: ${unions.join(', ')}`)
}

function generatedCode(): string {
  assertDropSafe()
  const names = Object.fromEntries(EXPORTS.map((name) => [`validate${name}`, `${name}#`]))
  const code = inlineUcs2length(standaloneCode.default(compiler(), names))
  const runtime = [...code.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1])
  if (runtime.length > 0) throw new Error(`unexpected runtime require(s) in generated code: ${runtime.join(', ')}`)
  const body = code.replace(/^"use strict";/, '')
  return `${HEADER}\nimport { fullFormats } from 'ajv-formats/dist/formats.js'\n${body}\n`
}

function generatedTypes(): string {
  const imports = EXPORTS.map((name) => (name === 'Error' ? 'Error as ErrorBody' : name)).join(', ')
  const lines = EXPORTS.map(
    (name) => `export declare const validate${name}: ValidateFunction<${name === 'Error' ? 'ErrorBody' : name}>`,
  )
  return [
    HEADER,
    "import type { ValidateFunction } from 'ajv'",
    `import type { ${imports} } from '../generated-types.ts'`,
    '',
    ...lines,
    '',
  ].join('\n')
}

const expected = { code: generatedCode(), types: generatedTypes() }
const KINDS = ['code', 'types'] as const
const stale = KINDS.filter((k) => !existsSync(targets[k]) || readFileSync(targets[k], 'utf8') !== expected[k])

if (!process.argv.includes('--check')) {
  for (const k of stale) writeFileSync(targets[k], expected[k])
  console.log(stale.length > 0 ? `wrote ${stale.map((k) => targets[k]).join(', ')}` : 'validators up to date')
} else if (stale.length > 0) {
  console.error('Generated validators are stale; run `pnpm --filter @sophia/contracts generate`')
  process.exit(1)
} else {
  console.log('Generated validators match OpenAPI')
}
